// Assembly
// ---------------------------------------------------------------------------------

/**
 * Generate the Layer 1 units.
 *
 * @returns {{ units: object[], errors: object, notes: string[], limits: object }}
 */
export function scaffoldLayer1(evidence, {
  areaCardLimit = DEFAULT_AREA_CARD_LIMIT,
  filesPerCard = 40,
  symbols = 40,
  externals = 20,
} = {}) {
  const limits = { areaCardLimit, filesPerCard, symbols, externals };
  const notes = [];
  const units = [];

  const areas = evidence.areas.filter((area) => area.fileCount > 0);
  if (areas.length > areaCardLimit) {
    notes.push(`${areas.length} areas found, ${areaCardLimit} carded; the cap is displayed rather than applied silently.`);
  }
  for (const area of areas.slice(0, areaCardLimit)) {
    units.push(architectureCard(area, evidence, limits));
  }

  if (evidence.dependencies.declaredCount > 0 || evidence.dependencies.undeclaredImports.length > 0) {
    units.push(dependencyCard(evidence));
  } else {
    notes.push('No dependency card: no manifest declared dependencies and no external imports were found.');
  }

  for (const card of CONVENTION_CARDS) {
    const measurement = evidence.conventions[card.key];
    // A convention with no denominator is not a convention, it is an absence. Emitting a
    // card that says "0 of 0 files" would put a claim in the brain that no measurement
    // supports, which is the failure mode this whole file is arranged against.
    if (!measurement?.dominant || measurement.measured.total === 0) {
      notes.push(`No ${card.key} convention card: nothing measurable (${measurement?.measured.display || '0 of 0'}).`);
      continue;
    }
    units.push(conventionCard(card, measurement));
  }
  if (evidence.testLayout.testFiles > 0) units.push(testLayoutCard(evidence.testLayout));
  else notes.push('No test-layout card: no test files found by path.');

  if (evidence.history.available && evidence.history.commits > 0) {
    units.push(historyCard(evidence.history));
  } else {
    notes.push(`No history card: ${evidence.history.reason || 'no commits walked'}.`);
  }

  // The errors record. EMPTY at Layer 1, always, and the reason is stated rather than
  // implied. The candidate lists ride alongside as evidence for the Layer 2 narration
  // step; nothing here turns one into a unit.
  const errors = {
    units: [],
    reason: evidence.history.available
      ? 'Layer 1 writes no error records. Fix and revert commits are candidate evidence only; a lesson enters the brain after narration validates it against the real commit, or after the gym earns it.'
      : 'errors.md starts empty: this repo has no history to mine, and inventing an error record is forbidden.',
    candidates: {
      fixCommits: evidence.history.fixCommits || [],
      revertCommits: evidence.history.revertCommits || [],
    },
  };

  // The provenance section is appended last so its digest covers the finished card.
  const finished = units.map((entry) => {
    const method = entry.type === 'workflow'
      ? 'git log --numstat walk, capped and reported'
      : entry.type === 'convention'
        ? 'statistical count over the tracked source files'
        : 'import graph and directory tree over the tracked source files';
    const content = `${entry.content}\n\n${provenanceSection(method, entry.meta.evidenceDigest)}`;
    return {
      ...entry,
      content,
      body: `${entry.body}\n\n${provenanceSection(method, entry.meta.evidenceDigest)}`,
      contentHash: sha256(content),
    };
  });

  return { units: finished, errors, notes, limits };
}

/**
 * Reject any unit citing something that is not there.
 *
 * This is the "mechanics accept" half of the plan's rule, and it runs on LAYER 1 output
 * too, not only on narration. A deterministic generator can still cite a stale path when
 * its inputs and the tree disagree (a file read from a cached listing, a path normalised
 * wrongly), and a citation nobody checks is indistinguishable from one nobody can check.
 *
 * @returns {{ accepted: object[], dropped: object[] }}
 */
export function validateCitations(units, { files = [], commits = new Set() } = {}) {
  const fileSet = new Set(files);
  const accepted = [];
  const dropped = [];
  for (const entry of units) {
    const missing = (entry.citations || []).filter((citation) => {
      if (/^[0-9a-f]{7,40}$/i.test(citation)) return !commits.has(citation);
      return !fileSet.has(citation);
    });
    if (missing.length > 0) dropped.push({ id: entry.id, missing });
    else accepted.push(entry);
  }
  return { accepted, dropped };
}
